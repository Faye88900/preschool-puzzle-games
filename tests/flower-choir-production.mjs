import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true });
const errors = [], output = 'test-results/flower-choir-production';
try {
  await mkdir(output, { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, hasTouch: true });
  page.setDefaultTimeout(90000);
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
  // Expose the instance in the browser test only; keep its real render, physics, and audio loops.
  await page.route(/\/assets\/maze-[^/]+\.js$/, async route => {
    const response = await route.fetch(), body = await response.text();
    const name = body.match(/export\{([\w$]+) as MazeAdventure\}/)?.[1]; assert.ok(name, 'Locate the built MazeAdventure export');
    await route.fulfill({ response, body: body + `\nconst originalInit=${name}.prototype.init;${name}.prototype.init=async function(){window.game=this;return originalInit.call(this)};` });
  });
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5209/?level=3&lang=zh');
  await page.locator('.journey-skip').click(); await page.locator('.game-loading').waitFor({ state: 'detached' });
  await page.locator('#primary').click();
  const initial = await page.evaluate(() => {
    const g = game; g.wand = g.bridgeOpen = true; g.bridgeProgress = 1; g.bridgeBody.setEnabled(false);
    g.enemies.forEach(e => e.hp = 0); g.encounterGateProgress = 1; g.encounterGate.body.setEnabled(false);
    g.body.setTranslation({ x: 75, y: .8, z: 0 }, true); g.body.setLinvel({ x: 0, y: 0, z: 0 }, true);
    g.previous.copy(g.body.translation()); g.render(0);
    const analyser = g.audio.context.createAnalyser(); analyser.fftSize = 256; g.flowerChoir.gain.connect(analyser); window.choirAnalyser = analyser;
    return { duration: g.flowerChoir.buffer.duration, context: g.audio.context.state, asleep: g.flowerChoir.status === 'sleeping', target: g.target().spot };
  });
  assert.ok(initial.asleep && initial.target === 'choir' && initial.context === 'running');
  await page.keyboard.press('KeyE');
  await page.waitForFunction(() => game.flowerChoir.elapsed > 10.7);
  const verse = await page.evaluate(() => {
    const data = new Float32Array(256); choirAnalyser.getFloatTimeDomainData(data);
    return { time: game.flowerChoir.elapsed, lyric: game.flowerChoir.line.getAttribute('aria-label'), signal: Math.max(...data.map(Math.abs)), source: !!game.flowerChoir.source };
  });
  assert.equal(verse.lyric, '风儿轻轻吹过来'); assert.ok(verse.signal > .001 && verse.source);
  await page.screenshot({ path: `${output}/verse-desktop.png` });
  await page.locator('#pause').click();
  const frozen = await page.evaluate(() => game.flowerChoir.elapsed);
  await page.waitForTimeout(500);
  assert.ok(await page.evaluate(t => game.paused && Math.abs(game.flowerChoir.elapsed - t) < .001, frozen));
  await page.locator('#primary').click();
  await page.waitForFunction(t => game.flowerChoir.elapsed > t + .2, frozen);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => game.flowerChoir.elapsed > 19.1);
  await page.screenshot({ path: `${output}/chorus-portrait.png` });
  await page.keyboard.down('KeyD'); await page.waitForTimeout(500); await page.keyboard.up('KeyD');
  assert.ok(await page.evaluate(() => game.body.translation().x > 75.3 && game.flowerChoir.performing && game.active()));
  await page.locator('#sound').click(); await page.waitForTimeout(700);
  assert.ok(await page.evaluate(() => game.muted && game.flowerChoir.gain.gain.value < .01));
  await page.locator('#sound').click(); await page.waitForTimeout(700);
  assert.ok(await page.evaluate(() => !game.muted && game.flowerChoir.gain.gain.value > .7));
  await page.waitForFunction(() => game.flowerChoir.elapsed > 39.6);
  await page.screenshot({ path: `${output}/thanks-portrait.png` });
  await page.evaluate(() => { window.loopingSource = game.flowerChoir.source; });
  await page.waitForFunction(() => game.flowerChoir.elapsed > game.flowerChoir.buffer.duration + .5);
  const loop = await page.evaluate(() => ({ time: game.flowerChoir.elapsed, playing: game.flowerChoir.performing, sameSource: game.flowerChoir.source === loopingSource, loop: game.flowerChoir.source.loop, awake: game.flowerChoir.flowers.every(f => f.head.rotation.x === 0), captionVisible: !game.flowerChoir.caption.hidden, music: game.audio.music.volume }));
  assert.ok(loop.playing && loop.sameSource && loop.loop && loop.awake && loop.captionVisible && loop.music === .035, JSON.stringify(loop));
  await page.screenshot({ path: `${output}/second-pass-portrait.png` });
  const left = await page.evaluate(() => {
    game.body.setTranslation({ x: game.chest.position.x, y: .8, z: game.chest.position.z + 2 }, true); game.previous.copy(game.body.translation()); game.render(0);
    return { source: !!game.flowerChoir.source, dozing: game.flowerChoir.status === 'dozing', captionHidden: game.flowerChoir.caption.hidden, music: game.audio.music.volume, target: game.target()?.spot };
  });
  assert.ok(!left.source && left.dozing && left.captionHidden && left.music === .22 && left.target === 'chest', JSON.stringify(left));
  await page.waitForFunction(() => game.flowerChoir.sleepTime > .5);
  const settling = await page.evaluate(() => ({ time: game.flowerChoir.sleepTime, head: game.flowerChoir.flowers[0].head.rotation.x, petals: game.flowerChoir.flowers[0].petals.scale.x }));
  assert.ok(settling.head > 0 && settling.head < .55 && settling.petals > .75 && settling.petals < 1, JSON.stringify(settling));
  await page.waitForFunction(() => game.flowerChoir.status === 'sleeping');
  await page.screenshot({ path: `${output}/stopped-at-chest-portrait.png` });
  await page.evaluate(() => { game.body.setTranslation({ x: 75, y: .8, z: 0 }, true); game.body.setLinvel({ x: 0, y: 0, z: 0 }, true); game.previous.copy(game.body.translation()); game.render(0); });
  assert.ok(await page.evaluate(() => game.flowerChoir.status === 'sleeping' && !game.flowerChoir.source));
  await page.locator('#dive').tap(); await page.waitForFunction(() => game.flowerChoir.performing && game.flowerChoir.elapsed > .2);
  assert.ok(await page.evaluate(() => game.flowerChoir.elapsed < 3));
  await page.screenshot({ path: `${output}/replay-portrait.png` });
  const resources = await page.evaluate(() => performance.getEntriesByType('resource').filter(e => e.name.endsWith('/audio/maze/flower-choir.mp3')).map(e => ({ name: e.name, bytes: e.decodedBodySize })));
  assert.equal(resources.length, 1); assert.ok(resources[0].bytes > 1000000);
  assert.deepEqual(errors, []);
  await writeFile(`${output}/report.json`, JSON.stringify({ initial, verse, frozen, loop, left, settling, resources, errors }, null, 2));
  console.log('PASS production full song loops naturally on the same audio source, stays awake, stops and sleeps on leaving, touch reactivation, timed lyrics, movement, pause/resume, mute/unmute, one song fetch', JSON.stringify({ initial, verse, loop, left, resources, errors }));
} finally { await browser.close(); }
